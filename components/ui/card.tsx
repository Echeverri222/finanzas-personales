import * as React from "react"

import { cn } from "@/lib/utils"

const Card = React.forwardRef<
  HTMLDivElement,
  React.HTMLAttributes<HTMLDivElement>
>(({ className, ...props }, ref) => (
  <div
    ref={ref}
    className={cn(
      // Upstream shadcn ships `rounded-xl shadow` here. Deliberately kept at
      // `rounded-lg shadow-sm`: this project overrides borderRadius.xl to
      // 1.5rem (24px) for hero surfaces, where upstream assumes ~0.85rem, so
      // `rounded-xl` would make all 13 card call sites drastically rounder.
      "rounded-lg border bg-card text-card-foreground shadow-sm",
      className
    )}
    {...props}
  />
))
Card.displayName = "Card"

